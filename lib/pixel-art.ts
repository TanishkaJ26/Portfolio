/**
 * The pixel-art atlas.
 *
 * Every sprite is a rectangular grid of characters — one character per pixel,
 * authored by hand. `components/ui/pixel.tsx` turns a grid into merged <rect>
 * runs, so a 12x12 glyph costs a handful of nodes and no network request.
 *
 * The character set is the design system, not an arbitrary palette:
 *
 *   .  transparent
 *   #  currentColor        — the sprite inherits the colour of its context,
 *                            which is what lets the stack list light a glyph
 *                            pink on hover without the sprite knowing about it
 *   o  currentColor @ 40%  — shading, bellies, fills
 *   +  --pink              — the one accent, as sparing here as everywhere
 *                            else: a couple of pixels per glyph
 *   O  --raised            — an opaque dark fill, for screens and panels that
 *                            need to occlude the dot-grid behind them
 *   =  --text-mute         — "text" inside a scene: code lines, chat, keys
 *
 * Grids must be rectangular. `npm run check:pixels` proves it, so a
 * miscounted row fails the build instead of rendering as a sheared sprite.
 */

export type PixelArt = readonly string[];

